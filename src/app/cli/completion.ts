/**
 * `reels completion <shell>`: a static completion script for this CLI version.
 * Generated when the command runs, from the same tables the router reads, so it
 * never lists a command or flag this version does not have. It installs nothing.
 *
 * Past the command word, flags are offered only for a word that starts with `-`.
 * Any other word, and the value of a flag that takes one, gets the command's own
 * positional words (help topics, tool slugs, shells) or else the shell's file
 * completion, so `--out <TAB>` and `--selection ./<TAB>` still complete paths.
 */
export const completionShells = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof completionShells)[number];

export type CompletionSpec = {
  version: string;
  /** Words for the first position: commands, tool slugs and global flags. */
  first: readonly string[];
  /**
   * Words after a command, by every spelling of that command. A tool after `call` uses its own entry.
   * `values` are its flags that take a value: after one of them only files are completed.
   */
  commands: readonly {
    names: readonly string[];
    words: readonly string[];
    values?: readonly string[];
  }[];
  /** Values offered right after `--group`. */
  groups: readonly string[];
};

/** Only these characters reach a script, so no word needs quoting in any shell. */
const safeWord = /^[A-Za-z0-9_.-]+$/;
function checked(words: readonly string[]) {
  for (const word of words)
    if (!safeWord.test(word))
      throw new Error(`Completion word needs quoting: ${word}`);
  return words.join(" ");
}

/** A command's words split into flags and positional words, and its value-taking flags. */
function parts({ words, values = [] }: CompletionSpec["commands"][number]) {
  return {
    flags: checked(words.filter((word) => word.startsWith("-"))),
    args: checked(words.filter((word) => !word.startsWith("-"))),
    values: checked(values),
  };
}

const header = (version: string, shell: string) =>
  `# reels completion for ${shell}, generated by reels ${version}. It lists this version's
# commands and flags: re-run \`reels completion ${shell}\` after updating Reels Dashboard.`;

function bash(spec: CompletionSpec) {
  const cases = spec.commands
    .map((command) => {
      const { flags, args, values } = parts(command);
      return `    ${checked(command.names).replaceAll(" ", "|")}) flags="${flags}" args="${args}" values="${values}" ;;`;
    })
    .join("\n");
  return `${header(spec.version, "bash")}
# Load it with: eval "$(reels completion bash)"
# An empty reply falls back to file names (complete -o default), as for paths after --out.
_reels() {
  local cur prev cmd words flags args values
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  words=""
  if [ "$COMP_CWORD" -eq 1 ]; then
    words="${checked(spec.first)}"
  elif [ "$prev" = "--group" ]; then
    words="${checked(spec.groups)}"
  else
    cmd="\${COMP_WORDS[1]}"
    if [ "$cmd" = "call" ] && [ "$COMP_CWORD" -ge 3 ]; then
      cmd="\${COMP_WORDS[2]}"
    fi
    flags="" args="" values=""
    case "$cmd" in
${cases}
    esac
    case " $values " in
      *" $prev "*) ;;
      *)
        case "$cur" in
          -*) words="$flags" ;;
          *) words="$args" ;;
        esac
        ;;
    esac
  fi
  COMPREPLY=( $(compgen -W "$words" -- "$cur") )
}
complete -o default -F _reels reels
`;
}

function zsh(spec: CompletionSpec) {
  const cases = spec.commands
    .map((command) => {
      const { flags, args, values } = parts(command);
      return `      ${checked(command.names).replaceAll(" ", "|")}) flags=(${flags}) args=(${args}) values=(${values}) ;;`;
    })
    .join("\n");
  return `#compdef reels
${header(spec.version, "zsh")}
# Save it as _reels in a folder on $fpath, or load it with: source <(reels completion zsh)
# Past the command word a word not starting with - (or a flag's value) falls back to _files.
_reels() {
  local cmd prev
  local -a candidates flags args values
  prev=\${words[CURRENT-1]}
  if (( CURRENT == 2 )); then
    candidates=(${checked(spec.first)})
  elif [[ $prev == --group ]]; then
    candidates=(${checked(spec.groups)})
  else
    cmd=\${words[2]}
    if [[ $cmd == call ]] && (( CURRENT >= 4 )); then
      cmd=\${words[3]}
    fi
    case $cmd in
${cases}
    esac
    if (( \${values[(Ie)$prev]} )); then
      _files
      return
    elif [[ $PREFIX == -* ]]; then
      candidates=($flags)
    elif (( \${#args} )); then
      candidates=($args)
    else
      _files
      return
    fi
  fi
  compadd -a candidates
}
if [ "$funcstack[1]" = "_reels" ]; then
  _reels "$@"
else
  compdef _reels reels
fi
`;
}

function fish(spec: CompletionSpec) {
  const lines = spec.commands.map(({ names, words }) => {
    const seen = `__fish_seen_subcommand_from ${checked(names)}`;
    return `complete -c reels -n '${seen}; and not __reels_after_group' -a '${checked(words)}'`;
  });
  return `${header(spec.version, "fish")}
# Save it as ~/.config/fish/completions/reels.fish, or load it with: reels completion fish | source
function __reels_after_group
    set -l tokens (commandline -opc)
    test (count $tokens) -ge 2; and test "$tokens[-1]" = --group
end
# -f (no file names) only where a word must be a command or a group; elsewhere files stay offered.
complete -c reels -f -n __fish_use_subcommand -a '${checked(spec.first)}'
complete -c reels -f -n __reels_after_group -a '${checked(spec.groups)}'
${lines.join("\n")}
`;
}

export function completionScript(shell: CompletionShell, spec: CompletionSpec) {
  return { bash, zsh, fish }[shell](spec);
}
